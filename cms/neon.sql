CREATE TABLE IF NOT EXISTS posts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(150) NOT NULL UNIQUE,
  title VARCHAR(180) NOT NULL,
  excerpt VARCHAR(500) NOT NULL,
  content_html TEXT NOT NULL,
  cover_image VARCHAR(300) NOT NULL,
  author VARCHAR(120) NOT NULL,
  category VARCHAR(80) NOT NULL,
  seo_title VARCHAR(180) NOT NULL,
  seo_description VARCHAR(300) NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('draft', 'published')),
  published_at TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS posts_status_date ON posts(status, published_at DESC);

CREATE TABLE IF NOT EXISTS press_articles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  outlet VARCHAR(120) NOT NULL,
  excerpt VARCHAR(500) NOT NULL,
  url VARCHAR(2000) NOT NULL,
  cover_image VARCHAR(300) NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('draft', 'published')),
  published_at TEXT,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS press_status_date ON press_articles(status, published_at DESC);

CREATE TABLE IF NOT EXISTS cms_images (
  filename VARCHAR(64) PRIMARY KEY,
