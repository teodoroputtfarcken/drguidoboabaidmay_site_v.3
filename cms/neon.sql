  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS cms_sessions_expiry ON cms_sessions(expires_at);
CREATE TABLE IF NOT EXISTS cms_migrations (name VARCHAR(100) PRIMARY KEY);

